CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    name_key VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE materials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    sku VARCHAR(255) UNIQUE,
    category_id BIGINT NOT NULL,
    unit VARCHAR(255),
    stock DECIMAL(16, 3),
    min_stock DECIMAL(16, 3),
    unit_cost DECIMAL(16, 4),
    active BOOLEAN NOT NULL,
    version BIGINT,
    FOREIGN KEY (category_id) REFERENCES categories(id)
);

CREATE TABLE movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id BIGINT NOT NULL,
    type VARCHAR(255) NOT NULL,
    quantity DECIMAL(16, 3) NOT NULL,
    before_stock DECIMAL(16, 3) NOT NULL,
    after_stock DECIMAL(16, 3) NOT NULL,
    reason VARCHAR(255) NOT NULL,
    username VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    FOREIGN KEY (material_id) REFERENCES materials(id)
);

CREATE INDEX idx_movements_material_id ON movements(material_id);

CREATE TABLE supplier (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    phone VARCHAR(255),
    email VARCHAR(255),
    notes VARCHAR(255)
);

CREATE TABLE material_changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id BIGINT NOT NULL,
    username VARCHAR(255) NOT NULL,
    changed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    field_name VARCHAR(255) NOT NULL,
    previous_value VARCHAR(255),
    new_value VARCHAR(255),
    FOREIGN KEY (material_id) REFERENCES materials(id)
);

CREATE INDEX idx_material_changes_history ON material_changes(material_id, changed_at, id);
