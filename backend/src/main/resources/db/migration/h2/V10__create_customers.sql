CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    contact VARCHAR(255),
    email VARCHAR(254),
    phone VARCHAR(64),
    address VARCHAR(500)
);

ALTER TABLE quotation_revisions ADD COLUMN customer_id BIGINT;
ALTER TABLE quotation_revisions ADD CONSTRAINT fk_quotation_revision_customer
    FOREIGN KEY (customer_id) REFERENCES customers(id);
