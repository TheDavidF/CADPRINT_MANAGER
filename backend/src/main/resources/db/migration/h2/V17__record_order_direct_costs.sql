CREATE TABLE order_direct_costs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_order_id BIGINT NOT NULL,
    request_id VARCHAR(36) NOT NULL,
    category VARCHAR(24) NOT NULL,
    description VARCHAR(255) NOT NULL,
    amount DECIMAL(27,2) NOT NULL,
    incurred_on DATE NOT NULL,
    recorded_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    recorded_by VARCHAR(255) NOT NULL,
    CONSTRAINT fk_order_direct_cost_order FOREIGN KEY (customer_order_id) REFERENCES customer_orders(id),
    CONSTRAINT uq_order_direct_cost_request UNIQUE (customer_order_id, request_id),
    CONSTRAINT ck_order_direct_cost_amount CHECK (amount > 0)
);
