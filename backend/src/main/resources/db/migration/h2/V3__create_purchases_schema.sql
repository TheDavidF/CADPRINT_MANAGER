CREATE TABLE purchases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT,
    purchase_date DATE NOT NULL,
    document_number VARCHAR(255),
    status VARCHAR(16) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    subtotal DECIMAL(19, 2) NOT NULL,
    total DECIMAL(19, 2) NOT NULL,
    notes VARCHAR(1000),
    created_by VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL,
    CONSTRAINT fk_purchases_supplier FOREIGN KEY (supplier_id) REFERENCES supplier(id),
    CONSTRAINT ck_purchases_status CHECK (status IN ('BORRADOR', 'PENDIENTE', 'RECIBIDA', 'CANCELADA')),
    CONSTRAINT ck_purchases_amounts CHECK (subtotal >= 0 AND total >= 0)
);

CREATE INDEX idx_purchases_supplier_document ON purchases(supplier_id, document_number);

CREATE TABLE purchase_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id BIGINT NOT NULL,
    material_id BIGINT NOT NULL,
    quantity DECIMAL(16, 3) NOT NULL,
    purchase_unit VARCHAR(255) NOT NULL,
    unit_price DECIMAL(19, 4) NOT NULL,
    subtotal DECIMAL(19, 2) NOT NULL,
    inventory_unit VARCHAR(255),
    conversion_factor DECIMAL(20, 9),
    inventory_quantity DECIMAL(16, 3),
    inventory_unit_cost DECIMAL(27, 8),
    CONSTRAINT fk_purchase_lines_purchase FOREIGN KEY (purchase_id) REFERENCES purchases(id),
    CONSTRAINT fk_purchase_lines_material FOREIGN KEY (material_id) REFERENCES materials(id),
    CONSTRAINT uq_purchase_lines_id_material UNIQUE (id, material_id),
    CONSTRAINT ck_purchase_lines_amounts CHECK (quantity > 0 AND unit_price > 0 AND subtotal >= 0),
    CONSTRAINT ck_purchase_lines_conversion CHECK (
        (inventory_unit IS NULL AND conversion_factor IS NULL AND inventory_quantity IS NULL AND inventory_unit_cost IS NULL)
        OR (inventory_unit IS NOT NULL AND conversion_factor IS NOT NULL AND conversion_factor > 0
            AND inventory_quantity IS NOT NULL AND inventory_quantity > 0
            AND inventory_unit_cost IS NOT NULL AND inventory_unit_cost >= 0)
    )
);

CREATE INDEX idx_purchase_lines_purchase ON purchase_lines(purchase_id);
CREATE INDEX idx_purchase_lines_material ON purchase_lines(material_id);

CREATE TABLE purchase_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id BIGINT NOT NULL,
    received_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    received_by VARCHAR(255) NOT NULL,
    CONSTRAINT fk_purchase_receipts_purchase FOREIGN KEY (purchase_id) REFERENCES purchases(id),
    CONSTRAINT uq_purchase_receipts_purchase UNIQUE (purchase_id)
);

CREATE TABLE purchase_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id BIGINT NOT NULL,
    event_type VARCHAR(40) NOT NULL,
    previous_status VARCHAR(16),
    new_status VARCHAR(16),
    username VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    reason VARCHAR(1000),
    CONSTRAINT fk_purchase_events_purchase FOREIGN KEY (purchase_id) REFERENCES purchases(id)
);

CREATE INDEX idx_purchase_events_history ON purchase_events(purchase_id, created_at, id);

